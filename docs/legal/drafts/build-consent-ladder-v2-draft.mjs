// Builds consent_membership_ladder_v2_DRAFT.sql from the three consent files, so
// the script and the signed text cannot drift apart.
//
//   node docs/legal/drafts/build-consent-ladder-v2-draft.mjs [version]
//
// With no version argument the output carries the SET-AT-PUBLISH placeholder
// and refuses to run. Pass the final version string only after the owner has
// signed. The patient text starts at the first "## " heading of each file;
// everything above it (the title and the italic draft banner) is not published.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const legal = join(here, "..");
// --check regenerates with the placeholder and fails if the committed file differs.
const check = process.argv.includes("--check");
const version = process.argv.slice(2).find((a) => a !== "--check") ?? "SET-AT-PUBLISH";
if (!/^[A-Za-z0-9._-]+$/.test(version)) throw new Error(`bad version string: ${version}`);

function patientText(file) {
  const text = readFileSync(join(legal, file), "utf8");
  const start = text.indexOf("\n## ");
  if (start === -1) throw new Error(`${file}: no "## " heading found`);
  return text.slice(start + 1).trim();
}

const terms = patientText("schedule-c-terms-of-service.md");
const telehealth = patientText("schedule-b-telehealth-consent.md");
const dataProcessing = patientText("schedule-a-data-processing-consent.md");

for (const [tag, body] of [
  ["tos_body", terms],
  ["tele_body", telehealth],
  ["dp_body", dataProcessing],
]) {
  if (body.includes(`$${tag}$`)) throw new Error(`body contains its own quote tag ${tag}`);
}

const banner =
  version === "SET-AT-PUBLISH"
    ? `-- DRAFT. NOT APPLIED. DO NOT APPLY until the owner has signed off
-- docs/legal/membership-terms-signoff.md. The version guard below
-- refuses to run while the placeholder is still SET-AT-PUBLISH, and the body
-- guards refuse a square bracket, an em dash, an en dash or a retired provider.`
    : `-- Publishes consent version ${version}. Signed off by the owner (CEO) in chat on
-- 2026-10-30; see docs/legal/membership-terms-signoff.md. The body guards below
-- refuse a square bracket, an em dash, an en dash or a retired provider.`;

const sql = `${banner}
--
-- GENERATED by docs/legal/drafts/build-consent-ladder-v2-draft.mjs from
-- docs/legal/schedule-c-terms-of-service.md and
-- docs/legal/schedule-b-telehealth-consent.md and
-- docs/legal/schedule-a-data-processing-consent.md. Edit those files, then
-- regenerate. Do not hand-edit the bodies below.
--
-- Publishes ALL THREE required consents in one transaction:
--   terms_of_service (Schedule C), telehealth (Schedule B) and
--   data_processing (Schedule A).
-- The 2026-10-13 script covered the Terms only, which would have left the
-- Telehealth Consent describing the old product. The optional consents
-- (research, sponsor_reporting and any draft) are left untouched, so prior
-- acceptances of them stay valid.
--
-- Shape of the table: public.consent_versions (id, consent_type, version,
-- title, body, is_current, published_at, created_at, text_key, is_optional,
-- is_draft, draft_note). Append-only by convention: a new row is inserted and
-- the old row's is_current is turned off. A published row is never edited
-- (private.protect_consent_version_text).
--
-- Effect on patients: all three are REQUIRED consents. Publishing a new current
-- version means every existing patient is asked to accept again at next
-- sign-in. That is the intended effect.
--
-- Apply only as execute_sql in ONE transaction with the schema_migrations row
-- inserted at this file's version (never bare apply_migration, which stamps
-- wall-clock time). Run list_migrations on the live project first and look for
-- anything recent you do not recognise. Never hand-type a round timestamp.
--
-- ROLLBACK: set each new row's is_current = false and the previous row's
-- is_current = true (never delete a published version).

do $$
declare
  v_version constant text := '${version}';
  v_terms_title text;
  v_tele_title text;
  v_dp_title text;
  v_terms_body text := $tos_body$
${terms}
$tos_body$;
  v_tele_body text := $tele_body$
${telehealth}
$tele_body$;
  v_dp_body text := $dp_body$
${dataProcessing}
$dp_body$;
  v_all text;
  v_other_before text;
  v_other_after text;
begin
  if v_version like 'SET-AT-PUBLISH%' then
    raise exception 'version is still the placeholder; the owner has not signed';
  end if;

  -- strict: raises if there is no current row, or more than one.
  select title into strict v_terms_title
    from public.consent_versions
   where consent_type = 'terms_of_service' and is_current;
  select title into strict v_tele_title
    from public.consent_versions
   where consent_type = 'telehealth' and is_current;
  select title into strict v_dp_title
    from public.consent_versions
   where consent_type = 'data_processing' and is_current;
  v_all := v_terms_body || v_tele_body || v_dp_body;

  if exists (select 1 from public.consent_versions
              where consent_type in ('terms_of_service', 'telehealth', 'data_processing')
                and version = v_version) then
    raise exception 'version % already exists for a consent being published', v_version;
  end if;

  -- Guards: refuse to publish a draft.
  if position('[' in v_all) > 0 then
    raise exception 'unresolved square-bracket placeholder in a consent body';
  end if;
  if v_all like '%' || chr(8212) || '%' or v_all like '%' || chr(8211) || '%' then
    raise exception 'em dash or en dash in a consent body';
  end if;
  if v_all ~* '(whatsapp|stripe|health wallet|platform credit)' then
    raise exception 'retired channel, provider or product named in a consent body';
  end if;
  if v_terms_body !~ '21-day refund' then
    raise exception 'terms body is missing the 21-day refund';
  end if;

  select md5(coalesce(string_agg(id::text, ',' order by id), ''))
    into v_other_before
    from public.consent_versions
   where is_current and consent_type not in ('terms_of_service', 'telehealth', 'data_processing');

  update public.consent_versions
     set is_current = false
   where consent_type in ('terms_of_service', 'telehealth', 'data_processing') and is_current;

  insert into public.consent_versions (consent_type, version, title, body, is_current)
  values ('terms_of_service', v_version, v_terms_title, v_terms_body, true),
         ('telehealth', v_version, v_tele_title, v_tele_body, true),
         ('data_processing', v_version, v_dp_title, v_dp_body, true);

  -- Assertions: provable, not hopeful.
  if (select count(*) from public.consent_versions
       where consent_type = 'terms_of_service' and is_current) <> 1 then
    raise exception 'exactly one terms_of_service version must be current';
  end if;
  if (select count(*) from public.consent_versions
       where consent_type = 'telehealth' and is_current) <> 1 then
    raise exception 'exactly one telehealth version must be current';
  end if;
  if not exists (select 1 from public.consent_versions
                  where consent_type = 'terms_of_service' and is_current
                    and version = v_version
                    and body like '%Membership Plus%'
                    and body like '%No automatic renewal%'
                    and body like '%no doctor has been alerted%') then
    raise exception 'new terms body is missing expected content';
  end if;
  if (select count(*) from public.consent_versions
       where consent_type = 'data_processing' and is_current) <> 1 then
    raise exception 'exactly one data_processing version must be current';
  end if;
  if not exists (select 1 from public.consent_versions
                  where consent_type = 'data_processing' and is_current
                    and version = v_version
                    and body like '%ndpc.gov.ng%'
                    and body like '%close your account%') then
    raise exception 'new data_processing body is missing expected content';
  end if;
  if not exists (select 1 from public.consent_versions
                  where consent_type = 'telehealth' and is_current
                    and version = v_version
                    and body like '%Free plan%') then
    raise exception 'new telehealth body is missing expected content';
  end if;

  select md5(coalesce(string_agg(id::text, ',' order by id), ''))
    into v_other_after
    from public.consent_versions
   where is_current and consent_type not in ('terms_of_service', 'telehealth', 'data_processing');
  if v_other_before is distinct from v_other_after then
    raise exception 'the other consent types were disturbed';
  end if;
end $$;
`;

const out = join(here, "consent_membership_ladder_v2_DRAFT.sql");
if (check) {
  if (readFileSync(out, "utf8") !== sql) {
    console.error("consent_membership_ladder_v2_DRAFT.sql is out of date; rerun this script");
    process.exit(1);
  }
  console.log("draft script matches the three consent files");
  process.exit(0);
}
writeFileSync(out, sql);
console.log(`wrote ${out} (${sql.length} chars, version ${version})`);
