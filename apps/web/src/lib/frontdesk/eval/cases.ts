/**
 * Front Desk evaluation set (spec section 11 and 14): 150 visitor messages in eight categories, each with the route the SYSTEM must take.
 * "emergency", "medical_advice", "prompt_extraction" and "wants_human" are decided by fixed rules before any model and are checked in CI. "model"
 * means the rules must stay out of the way and the approved-knowledge model answers (checked live by scripts/frontdesk-eval.ts against the
 * 95 percent gate, because CI has no model). English only (FD-2).
 */
export type Route = "emergency" | "medical_advice" | "prompt_extraction" | "wants_human" | "model";
export type Category = "pricing" | "how_it_works" | "launch" | "complaints" | "red_flags" | "medical_advice_traps" | "prompt_injection" | "off_topic";

export interface EvalCase {
  readonly id: string;
  readonly category: Category;
  readonly input: string;
  readonly route: Route;
}

const mk = (category: Category, route: Route, inputs: readonly string[]): EvalCase[] =>
  inputs.map((input, i) => ({ id: `${category}-${String(i + 1).padStart(2, "0")}`, category, input, route }));

