/**
 * Pure helpers behind `scripts/generate-controlled-medicine-fallback.ts` and the test that keeps `controlled-medicine-terms.generated.ts` honest (OQ-484).
 * The fallback is generated from the rows that seed `public.controlled_medicine_terms` (between the BEGIN SEED / END SEED markers in the migration that
 * created it), or from the live table with `--live`. Nobody types it.
 */
import type { ControlledMedicineTerm } from "./controlled-medicine-list";

export const SEED_MIGRATION = "20261030123840_controlled_medicine_list_one_governed_table.sql";

const ROW = /^\s*\('([a-z0-9][a-z0-9 -]*)',\s*'(narcotic|restricted)',\s*'([^']+)'\)\s*,?\s*$/;

/** The seed rows of the migration, in order. Throws if the markers are missing or a line between them is not a row. */
export function parseSeedTerms(sql: string): ControlledMedicineTerm[] {
  const start = sql.indexOf("-- BEGIN SEED controlled_medicine_terms");
  const end = sql.indexOf("-- END SEED controlled_medicine_terms");
  if (start < 0 || end < 0 || end < start) throw new Error("seed markers not found in the migration");
  const terms: ControlledMedicineTerm[] = [];
  for (const line of sql.slice(start, end).split("\n").slice(1)) {
    if (!line.trim()) continue;
    const match = ROW.exec(line);
    if (!match) throw new Error(`unreadable seed row: ${line}`);
    terms.push({ term: match[1], tier: match[2] as ControlledMedicineTerm["tier"], label: match[3] });
  }
  if (terms.length === 0) throw new Error("no seed rows found");
  return terms;
}

export function renderFallbackFile(terms: readonly ControlledMedicineTerm[], source: string, version: number): string {
  const rows = [...terms]
    .sort((a, b) => a.term.localeCompare(b.term))
    .map((t) => `  { term: ${JSON.stringify(t.term)}, tier: ${JSON.stringify(t.tier)}, label: ${JSON.stringify(t.label)} },`)
    .join("\n");
  return `// GENERATED by apps/web/scripts/generate-controlled-medicine-fallback.ts from ${source}. Do not edit by hand.
// This is only the offline fallback for the controlled-medicine guard (OQ-484). The list lives in public.controlled_medicine_terms and is read through
// get_controlled_medicine_list(); change it there (Chief Medical Officer), then regenerate this file with \`pnpm --filter @tarragon/web controlled-medicine-fallback --live\`.
import type { ControlledMedicineTerm } from "./controlled-medicine-list";

export const CONTROLLED_MEDICINE_FALLBACK_VERSION = ${version};

export const CONTROLLED_MEDICINE_FALLBACK: readonly ControlledMedicineTerm[] = [
${rows}
];
`;
}
