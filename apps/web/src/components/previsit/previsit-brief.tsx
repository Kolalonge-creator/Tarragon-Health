"use client";

import { useState } from "react";
import { Badge } from "@/components/ui/badge";
import { sourceAnchor, type BriefLine, type SourceRef } from "@/lib/previsit/brief";

const KIND_LABEL: Record<SourceRef["kind"], string> = {
  vitals_reading: "Reading",
  medication: "Medicine",
  care_task: "Task",
  care_gap: "Care gap",
  care_plan: "Care plan",
  consultation: "Consultation",
};

const when = (iso: string | null): string =>
  iso ? new Date(iso).toLocaleString("en-GB", { day: "numeric", month: "short", year: "numeric", timeZone: "Africa/Lagos" }) : "no date";

/**
 * Renders the deterministic brief. Each line has a "Sources" control that opens the exact rows it came from (kind, date, the row's own
 * content and id) and scrolls to and highlights the same row elsewhere on the page when one carries the matching anchor id.
 * Nothing here is generated by a model.
 */
export function PreVisitBriefView({ lines }: { lines: readonly BriefLine[] }) {
  const [openKey, setOpenKey] = useState<string | null>(null);
  const [highlight, setHighlight] = useState<string | null>(null);

  function show(ref: SourceRef) {
    const anchor = sourceAnchor(ref);
    setHighlight(anchor);
    const el = typeof document !== "undefined" ? document.getElementById(anchor) : null;
    el?.scrollIntoView?.({ behavior: "smooth", block: "center" });
  }

  return (
    <div data-testid="previsit-brief">
      <p className="text-xs font-medium uppercase tracking-wide text-charcoal-ink/50">Brief from the record</p>
      <ul className="mt-1 space-y-2">
        {lines.map((l) => (
          <li key={l.key} data-line={l.key} className="text-xs text-charcoal-ink/80">
            <span className="font-medium">{l.label}: </span>
            <span className={l.status === "ok" ? "" : "text-charcoal-ink/60"}>{l.text}</span>
            {l.sources.length > 0 && (
              <button
                type="button"
                className="ml-2 underline"
                aria-expanded={openKey === l.key}
                onClick={() => setOpenKey(openKey === l.key ? null : l.key)}
              >
                Sources ({l.sources.length})
              </button>
            )}
            {openKey === l.key && (
              <ul className="mt-1 space-y-1 rounded-md bg-charcoal-ink/5 p-2" aria-label={`${l.label} sources`}>
                {l.sources.map((s) => {
                  const anchor = sourceAnchor(s);
                  return (
                    <li key={anchor} id={anchor} className={highlight === anchor ? "rounded bg-amber-100 px-1" : "px-1"}>
                      <button type="button" className="text-left underline" onClick={() => show(s)}>
                        <Badge variant="grey">{KIND_LABEL[s.kind]}</Badge> {s.summary}
                      </button>
                      <span className="ml-2 text-charcoal-ink/50">{when(s.at)} · id {s.id}</span>
                    </li>
                  );
                })}
              </ul>
            )}
          </li>
        ))}
      </ul>
    </div>
  );
}
